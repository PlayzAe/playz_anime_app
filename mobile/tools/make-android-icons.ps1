# Generates the Android launcher icon set and the launch screen from the
# PlayzAnime seal, so the phone build wears the same mark as the desktop app.
#
#   powershell -ExecutionPolicy Bypass -File tools/make-android-icons.ps1
#
# Writes into android/app/src/main/res/. Re-runnable; it overwrites.

Add-Type -AssemblyName System.Drawing

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$res  = Join-Path $root 'android\app\src\main\res'
$src  = Join-Path $root 'build\icon-shu.png'   # the default accent, 512x512

if (-not (Test-Path $src)) { throw "missing $src" }

# Android densities, as a multiplier of the 48dp baseline.
$densities = [ordered]@{
  'mdpi'    = 1
  'hdpi'    = 1.5
  'xhdpi'   = 2
  'xxhdpi'  = 3
  'xxxhdpi' = 4
}

# Adaptive icons are a 108dp canvas; the mark may only occupy the inner 72dp,
# and Android may crop to a circle, so we draw at ~64% and centre it.
$safeZone = 0.62

$source = [System.Drawing.Image]::FromFile($src)

function Resize-Png {
  param([System.Drawing.Image]$Image, [int]$Size, [string]$Out, [double]$Scale = 1.0)

  $bmp = New-Object System.Drawing.Bitmap($Size, $Size, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
  $g = [System.Drawing.Graphics]::FromImage($bmp)
  $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
  $g.PixelOffsetMode   = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
  $g.SmoothingMode     = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
  $g.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality

  $inner = [int]($Size * $Scale)
  $off   = [int](($Size - $inner) / 2)
  $g.DrawImage($Image, $off, $off, $inner, $inner)
  $g.Dispose()

  $dir = Split-Path -Parent $Out
  if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
  $bmp.Save($Out, [System.Drawing.Imaging.ImageFormat]::Png)
  $bmp.Dispose()
}

foreach ($d in $densities.Keys) {
  $m = $densities[$d]
  $dir = Join-Path $res "mipmap-$d"

  # The legacy square/round icon: the whole seal, edge to edge.
  Resize-Png -Image $source -Size ([int](48 * $m)) -Out (Join-Path $dir 'ic_launcher.png')

  # The adaptive foreground layer: the seal inset into the safe zone.
  Resize-Png -Image $source -Size ([int](108 * $m)) -Out (Join-Path $dir 'ic_launcher_foreground.png') -Scale $safeZone
}

$source.Dispose()

# The adaptive icon points at the accent-coloured background and the inset seal.
$anydpi = Join-Path $res 'mipmap-anydpi-v26'
if (-not (Test-Path $anydpi)) { New-Item -ItemType Directory -Path $anydpi -Force | Out-Null }

$adaptive = @'
<?xml version="1.0" encoding="utf-8"?>
<!-- The vermilion seal: a solid accent plate with the carved mark on top.
     Regenerated by tools/make-android-icons.ps1. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
'@
Set-Content -Path (Join-Path $anydpi 'ic_launcher.xml') -Value $adaptive -Encoding UTF8

# Shutoku: the seal's own colour, so the plate and the mark agree.
$values = Join-Path $res 'values'
if (-not (Test-Path $values)) { New-Item -ItemType Directory -Path $values -Force | Out-Null }

$colors = @'
<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- Shu, the seal ink. Kept in step with AccentKey.shu in lib/theme/accent.dart. -->
    <color name="ic_launcher_background">#F0532C</color>
    <!-- The app opens on its own ink black, not on white. -->
    <color name="launch_background">#0C0B0A</color>
</resources>
'@
Set-Content -Path (Join-Path $values 'colors.xml') -Value $colors -Encoding UTF8

Write-Host "icons written to $res"
Get-ChildItem -Recurse $res -Filter 'ic_launcher*' | Select-Object -ExpandProperty FullName
